function k = cost_coefficients(s)
%COST_COEFFICIENTS  Objective coefficients of the LP for scenario s.
%
% Used by build_and_solve.m (objective vector) and by postprocess.m (cost
% breakdown), so that both always use the same numbers.
%
%   k.pv_capex, k.pv_om        $/yr per kWp of PV
%   k.b_capex_E, k.b_om_E      $/yr per kWh of battery energy capacity
%   k.b_capex_P, k.b_om_P      $/yr per kW of battery power (PCS) rating
%   k.d_capex                  $/yr per kW of diesel rating
%   k.grid                     $/kWh imported from the grid
%   k.fuel_u, k.fuel_p         fuel cost: $/h per kW committed, $/kWh generated
%   k.dg_om                    $/kWh generated by the diesel set
%   k.deg                      $/kWh discharged from the battery
%   k.ch                       $/kWh charged (0 unless a small cost is wanted)

k.crf_pv = crf(s.i, s.n_pv);
k.crf_b  = crf(s.i, s.n_b);
k.crf_d  = crf(s.i, s.n_d);

% PV: annualized capex + fixed O&M
k.pv_capex = k.crf_pv * s.c_pv;
k.pv_om    = s.om_pv;

% Battery: either the all-in $/kWh on E_b, or the energy + PCS split (not both)
switch s.batt_cost_mode
    case 'allin'
        cE = s.c_b_allin;  cP = 0;
    case 'split'
        cE = s.c_bE;       cP = s.c_bP;
    otherwise
        error('cost_coefficients:mode', 'Unknown batt_cost_mode "%s".', s.batt_cost_mode);
end
k.b_capex_E = k.crf_b * cE;
k.b_capex_P = k.crf_b * cP;
k.b_om_E    = s.om_b_frac * cE;    % fixed O&M as a fraction of capex per year
k.b_om_P    = s.om_b_frac * cP;

% Diesel: annualized capex (0 in the base case: existing sets are a sunk cost)
k.d_capex = k.crf_d * s.c_d;

% Operation
k.grid   = s.c_grid;
k.fuel_u = s.price_diesel * s.fuel_a;   % F(t) = a u_dg(t) + b p_dg(t)  [L/h]
k.fuel_p = s.price_diesel * s.fuel_b;
k.dg_om  = s.om_dg;
k.deg    = s.c_deg;
k.ch     = s.c_ch;
end
