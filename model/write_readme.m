% =========================================================================
function md_runs(fid, K, with_group)
% Markdown table of runs.
fprintf(fid, ['| Case | PV kWp | BESS kWh | Diesel kW | Cost $/yr | LCOE $/kWh | Saving | Saving without ' ...
              'throughput cost | Renewable | Diesel MWh | LPSP |\n']);
fprintf(fid, '|---|---|---|---|---|---|---|---|---|---|---|\n');
for j = 1:numel(K)
    k = K(j);
    if ~k.ok
        fprintf(fid, '| %s | not solved | | | | | | | | | |\n', k.name);
        continue
    end
    name = k.label;
    if with_group && ~strcmp(k.group, 'Base'), name = [k.group ': ' k.label]; end
    fprintf(fid, '| %s | %s | %s | %.0f | %s | %.3f | %.1f%% | %.1f%% | %.1f%% | %.0f | %.2f%% |\n', name, ...
            commas(k.P_pv), commas(k.E_b), k.P_d, commas(k.cost), k.lcoe, 100 * k.savings_frac, ...
            100 * k.savings_no_deg_frac, 100 * k.re_frac, k.E_diesel / 1000, 100 * k.lpsp);
end
fprintf(fid, '\n');
end

% =========================================================================
function str = run_name(K)
% Display name of a run: its group and label.
if strcmp(K.group, 'Base'), str = K.label; else, str = [K.group ': ' K.label]; end
end

% =========================================================================
function F = fin_of(fin, name)
j = find(strcmp({fin.name}, name), 1);
if isempty(j), F = []; else, F = fin(j).F; end
end

% =========================================================================
function str = ftxt(F, field, kind)
% One finance number as text: 'c' = with thousands separators, '%' = percent,
% 'y' = years. 'n/a' when it does not exist (no IRR, no payback in the horizon).
if isempty(F) || isnan(F.(field))
    str = 'n/a';
elseif kind == 'c'
    str = commas(F.(field));
elseif kind == '%'
    str = sprintf('%.1f%%', 100 * F.(field));
else
    str = sprintf('%.1f', F.(field));
end
end

% =========================================================================
function str = when(tl, hour)
% Local time stamp of an hour index.
if isnan(hour), str = 'none'; else, str = tl{hour}; end
end

% =========================================================================
function str = day_of(tl, hour)
% Local date (yyyy-mm-dd) of an hour index.
if isnan(hour), str = 'none'; else, str = tl{hour}(1:10); end
end

% =========================================================================
function str = list_of(v, fmt)
% Numbers as a comma-separated list.
if nargin < 2, fmt = '%.2f'; end
c = cell(1, numel(v));
for j = 1:numel(v), c{j} = sprintf(fmt, v(j)); end
str = strjoin(c, ', ');
end
