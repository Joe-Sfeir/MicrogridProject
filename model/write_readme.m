function write_readme(fname, S)
%WRITE_README  Write results/README.md from the results struct of main.m.
%
%   write_readme(fname, S)
%
% Every number in the text is computed from S or read from parameters.json;
% nothing is typed in. Statements that depend on the outcome are either
% written with the computed value or left out.

full = ~isempty(S.Ksens);
B = S.Kbase;  F = S.Kref;  s = S.base;  P = S.D.par;
tl = S.D.load.base.time_local;
Fb = S.fin(1).F;                               % finance of the base case
fid = fopen(fname, 'w');
p = @(varargin) fprintf(fid, varargin{:});

p('# Results: Faqra Club PV + battery microgrid (LP model)\n\n');
p('Written by `model/main.m` on %s with %s. Solver: %s. ', S.info.date, S.info.software, S.info.solver);
p('Run time %.0f s. Do not edit by hand: re-run `main` to regenerate every file in this folder. ', S.info.run_time);
p('The briefs are `docs/fable_prompt.md` and `docs/fable_prompt_round2.md`.\n\n');
if ~isempty(strfind(S.info.software, 'Octave')) %#ok<STREMP>
    p(['**These numbers were produced with GNU Octave and HiGHS, not with MATLAB.** The model code is the ' ...
       'same; in MATLAB `solve_lp.m` calls `linprog`. Re-run `main` in MATLAB before quoting the numbers ' ...
       'in the paper. The optimal cost of an LP is unique, so the costs should agree; sizes and the hourly ' ...
       'dispatch can differ slightly where several solutions are equally cheap. From R2024a `linprog` ' ...
       'uses HiGHS by default; with older releases it uses another dual simplex, whose run time on this ' ...
       'problem has not been tested: start with `main(''quick'')`.\n\n']);
end
if ~full
    p(['**Quick run:** only the reference, the base case and its finance metrics were computed. Run ' ...
       '`main` for the full study.\n\n']);
end

% ============================================================ base case
p('## Base case\n\n');
p(['Base load (club + chalets, %s MWh/yr, peak %.0f kW), measured EDL feeder availability, base ' ...
   'irradiance with snow loss, all parameters at base. LPSP limit %g%%'], commas(B.E_load / 1000), ...
   B.peak_load, 100 * s.lpsp_max);
if s.lpsp_max == 0, p(' (no load may be shed)'); end
p(['. The battery keeps %g kWh above its minimum from the start to the end of every hour in which the ' ...
   'T1 chairlift runs. PV tilt %d deg is the cheapest of the %d tilts.\n\n'], s.E_res, S.best_tilt, ...
   numel(S.tilts));
p('| | Reference (grid + diesel) | Base case (PV + battery + grid + diesel) |\n|---|---|---|\n');
p('| PV | 0 | %s kWp |\n', commas(B.P_pv));
p('| Battery | 0 | %s kWh / %s kW |\n', commas(B.E_b), commas(B.P_b));
p('| Diesel rating needed | %.0f kW | %.0f kW |\n', F.P_d, B.P_d);
p('| Annualized cost | %s $/yr | %s $/yr |\n', commas(F.cost), commas(B.cost));
p('| LCOE | %.3f $/kWh | %.3f $/kWh |\n', F.lcoe, B.lcoe);
p('| Annualized cost without the battery throughput cost | %s $/yr | %s $/yr |\n', commas(F.cost_no_deg), ...
  commas(B.cost_no_deg));
p('| Grid energy | %s MWh | %s MWh |\n', commas(F.E_grid / 1000), commas(B.E_grid / 1000));
p('| Diesel energy | %s MWh | %s MWh |\n', commas(F.E_diesel / 1000), commas(B.E_diesel / 1000));
p('| Fuel | %s L | %s L |\n', commas(F.fuel_L), commas(B.fuel_L));
p('| Renewable fraction (PV used on site / load) | 0%% | %.1f%% |\n', 100 * B.re_frac);
p('| PV curtailed | | %.1f%% of available PV |\n', 100 * B.curt_frac);
p('| LPSP achieved | %.2f%% | %.2f%% |\n', 100 * F.lpsp, 100 * B.lpsp);
p('| Unserved critical load | %.1f kWh | %.1f kWh |\n', F.E_uns_c, B.E_uns_c);
p('| Battery cycles | | %.0f per year |\n', B.cycles);
p('| CO2 | %s t/yr | %s t/yr |\n\n', commas(F.co2_t), commas(B.co2_t));
p('Saving against the reference: **%s $/yr (%.1f%%)**, and %s t CO2 per year.\n\n', ...
  commas(B.savings), 100 * B.savings_frac, commas(B.co2_saved_t));
p('Cost breakdown of the base case ($/yr): PV capex %s, PV O&M %s, battery capex %s, battery O&M %s, ', ...
  commas(B.c_pv_capex), commas(B.c_pv_om), commas(B.c_b_capex), commas(B.c_b_om));
p('battery throughput %s, diesel capex %s, fuel %s, diesel O&M %s, grid energy %s.\n\n', ...
  commas(B.c_b_deg), commas(B.c_d_capex), commas(B.c_fuel), commas(B.c_dg_om), commas(B.c_grid));
p(['**Battery wear is in the annualized cost twice.** The battery capex is recovered over its %d-year ' ...
   'calendar life, and each kWh discharged also costs %.3f $ (throughput cost). Both pay for wear. Cycle ' ...
   'life is not the limit: %.0f cycles per year over %d years is %s cycles, against %s for the cells. ' ...
   'The throughput cost stays in the LP because it stops pointless cycling. Costs with it are the ' ...
   'conservative figures; without it the base case costs %s $/yr and saves %s $/yr (%.1f%%). The tables ' ...
   'give both.\n\n'], s.n_b, s.c_deg, B.cycles, s.n_b, commas(B.cycles * s.n_b), ...
   commas(P.battery.cycles(2)), commas(B.cost_no_deg), commas(B.savings_no_deg), 100 * B.savings_no_deg_frac);
p(['Finance over %d years at a real discount rate of %.2f%%: investment %s $, **NPV %s $, real IRR ' ...
   '%.1f%%, simple payback %.1f years, discounted payback %.1f years** (section "Finance").\n\n'], ...
   Fb.horizon, 100 * Fb.rate, commas(Fb.capex0), commas(Fb.npv), 100 * Fb.irr, Fb.payback, Fb.payback_disc);

% ============================================================= shedding
if full
    Kl = S.Ksens(strcmp({S.Ksens.group}, 'LPSP limit'));
    p('## Why the base case allows no load shedding\n\n');
    p(['The first round used an LPSP limit of 1%%. The table shows where the model puts the shedding when ' ...
       'it is allowed. Only non-critical load is shed.\n\n']);
    p(['| Case | Shed MWh | Hours | Largest shed hour | On ski days | In Dec-Mar | In the worst 7 days ' ...
       '(starting) | Diesel kW | Cost saving vs base $/yr |\n|---|---|---|---|---|---|---|---|---|\n']);
    for j = 1:numel(Kl)
        k = Kl(j);
        if ~k.ok, continue; end
        p('| %s | %.1f | %d | %.0f kW, %s | %.0f%% | %.0f%% | %.0f%% (%s) | %.0f | %s |\n', k.label, ...
          (k.E_uns_c + k.E_uns_n) / 1000, k.uns_hours, k.uns_max_kW, when(tl, k.uns_max_hour), ...
          100 * k.uns_ski_frac, 100 * k.uns_winter_frac, 100 * k.uns_week_frac, day_of(tl, k.uns_week_start), ...
          k.P_d, commas(B.cost - k.cost));
    end
    k1 = Kl(find(abs([Kl.lpsp] - 0.01) < 1e-6 & ~strcmp({Kl.name}, 'lpsp1_offpeak'), 1));
    if ~isempty(k1)
        p(['\nWith a 1%% limit, %.0f%% of the shed energy falls on ski days and %.0f%% within seven ' ...
           'consecutive days starting %s; up to %.0f kW is shed at a time, against a peak load of %.0f kW. '], ...
          100 * k1.uns_ski_frac, 100 * k1.uns_week_frac, day_of(tl, k1.uns_week_start), k1.uns_max_kW, ...
          B.peak_load);
        p(['The whole allowance is worth %s $/yr. This is why the base case now requires that no load ' ...
           'is shed.\n\n'], commas(B.cost - k1.cost));
    end
    p(['The mechanism: every kWh that is shed saves the same diesel cost (%.3f $/kWh), whatever the ' ...
       'hour, so *when* to shed is a tie in cost. The diesel rating has no cost either (existing sets), ' ...
       'and the tie-breaker of %g $/kW-yr on it decides: the model sheds in the hours with the highest ' ...
       'diesel output, because that lowers the rating it reports (the "Diesel kW" column). The ' ...
       'reference case has the same LPSP limit as the case it is compared with, so it also changed to ' ...
       'no shedding.\n\n'], ...
       s.price_diesel * (s.fuel_a + s.fuel_b) + s.om_dg, s.tie);
    ko = Kl(strcmp({Kl.name}, 'lpsp1_offpeak'));
    if ~isempty(ko) && ko.ok
        p(['`lpsp1_offpeak` allows 1%% of the load to be shed but never on a ski day. It sheds %.1f MWh ' ...
           'in %d hours (%.0f%% in December to March), saves %s $/yr against the base case, and needs ' ...
           'a diesel rating of %.0f kW (base case %.0f kW). Which of the other hours it sheds is ' ...
           'again a tie in cost: the pattern in the table is one of many that cost the same.\n\n'], ...
           (ko.E_uns_c + ko.E_uns_n) / 1000, ko.uns_hours, 100 * ko.uns_winter_frac, ...
           commas(B.cost - ko.cost), ko.P_d, B.P_d);
    end
end

% ================================================================= tilt
p('## PV tilt\n\n');
md_runs(fid, S.Ktilt, false);
ct = sort([S.Ktilt.cost]);
p('The two cheapest tilts differ by %s $/yr (%.2f%% of the cost).\n\n', commas(ct(2) - ct(1)), ...
  100 * (ct(2) - ct(1)) / ct(1));

if full
    % ======================================================== sensitivities
    p('## Sensitivities (one change at a time from the base case)\n\n');
    p(['"Saving" compares each case with its own reference, that is grid + diesel only under the same ' ...
       'load, grid availability, prices and LPSP limit.\n\n']);
    md_runs(fid, [B, S.Ksens], true);
    Kq = S.Ksens(strcmp({S.Ksens.group}, 'Load'));
    if ~isempty(Kq)
        p(['Across the load scenarios and the base case the cost ranges from %s to %s $/yr and the LCOE ' ...
           'from %.3f to %.3f $/kWh.\n\n'], commas(min([Kq.cost, B.cost])), commas(max([Kq.cost, B.cost])), ...
           min([Kq.lcoe, B.lcoe]), max([Kq.lcoe, B.lcoe]));
    end
    kr = S.Ksens(strcmp({S.Ksens.name}, 'no_T1_reserve'));
    if ~isempty(kr) && kr.ok
        p(['The T1 lift reserve of %g kWh costs %s $/yr: the base case costs %s $/yr with it and %s $/yr ' ...
           'without (`no_T1_reserve`).\n\n'], s.E_res, commas(round(B.cost) - round(kr.cost)), ...
           commas(B.cost), commas(kr.cost));
    end
    bad = S.Ksens(~[S.Ksens.ok]);
    for j = 1:numel(bad)
        p('- `%s` did not solve (infeasible or solver error).\n', bad(j).name);
    end
    if ~isempty(bad), p('\n'); end

    % ========================================================= diesel sweep
    p('## Diesel price sweep\n\n');
    dp = P.diesel.price_per_L;
    p(['Sizes re-optimized at each price, each compared with the reference at the same price. The ' ...
       'observed Lebanese range in 2023-2026 is %.2f to %.2f $/L; the base price is %.2f $/L.\n\n'], ...
       dp(1), dp(3), dp(2));
    p(['| Diesel $/L | PV kWp | BESS kWh | Diesel kW | Grid MWh | Diesel MWh | Cost $/yr | Saving $/yr | ' ...
       'Saving | NPV $ | IRR | Discounted payback yr |\n|---|---|---|---|---|---|---|---|---|---|---|---|\n']);
    for j = 1:numel(S.Ksweep)
        k = S.Ksweep(j);  Fj = fin_of(S.fin, k.name);
        p('| %.2f | %s | %s | %.0f | %.0f | %.0f | %s | %s | %.1f%% | %s | %s | %s |\n', ...
          S.sweep(j).price_diesel, commas(k.P_pv), commas(k.E_b), k.P_d, k.E_grid / 1000, ...
          k.E_diesel / 1000, commas(k.cost), commas(k.savings), 100 * k.savings_frac, ...
          ftxt(Fj, 'npv', 'c'), ftxt(Fj, 'irr', '%'), ftxt(Fj, 'payback_disc', 'y'));
    end
    be_b   = (s.c_grid - s.om_dg) / s.fuel_b;                    % slope term only
    be_ab  = (s.c_grid - s.om_dg) / (s.fuel_a + s.fuel_b);       % with the no-load term at full load
    pr = [S.sweep.price_diesel];  Eg = [S.Ksweep.E_grid] / 1000;
    p(['\nBreak-even of own diesel against EDL energy: `diesel.breakeven_vs_edl_per_L` = %.3f $/L, ' ...
       'which counts the slope of the fuel curve only, (%.2f - %.4f) / %.3f = %.3f $/L. The LP runs the ' ...
       'sets at full load of what is committed, so its own break-even includes the no-load term: ' ...
       '(%.2f - %.4f) / (%.3f + %.3f) = %.3f $/L. Below it diesel energy is cheaper than grid energy. '], ...
       P.diesel.breakeven_vs_edl_per_L, s.c_grid, s.om_dg, s.fuel_b, be_b, s.c_grid, s.om_dg, s.fuel_a, ...
       s.fuel_b, be_ab);
    lo = pr < be_ab;
    if any(lo) && any(~lo)
        p(['In the sweep, grid import is at most %.1f MWh at the prices below it (%s $/L) and at least ' ...
           '%.0f MWh at the prices above it (from %.2f $/L).\n\n'], max(Eg(lo)), list_of(pr(lo)), ...
           min(Eg(~lo)), min(pr(~lo)));
    else
        p('\n\n');
    end

    % =============================================================== export
    Ke = S.Ksens(strcmp({S.Ksens.group}, 'Grid export'));
    p('## Grid export (sensitivity; the base case has no export)\n\n');
    p(['PV surplus may be exported while the feeder is on, within the connection capacity shared with ' ...
       'import (4''), and only PV is exported (4''''). Net metering credits each exported kWh at the ' ...
       'tariff, up to the year''s import (4''''''): the rest is forfeited. The price sweep sells every ' ...
       'exported kWh at the given price with no annual cap. Sizes are re-optimized in every case.\n\n']);
    p(['| Case | Exported MWh | Grid import MWh | Curtailed (base %.1f%%) | PV kWp (change) | BESS kWh ' ...
       '(change) | Cost $/yr | Saving $/yr | Saving | NPV $ |\n|---|---|---|---|---|---|---|---|---|---|\n'], ...
       100 * B.curt_frac);
    p('| Base case, no export | 0 | %.0f | %.1f%% | %s | %s | %s | %s | %.1f%% | %s |\n', B.E_grid / 1000, ...
      100 * B.curt_frac, commas(B.P_pv), commas(B.E_b), commas(B.cost), commas(B.savings), ...
      100 * B.savings_frac, commas(Fb.npv));
    for j = 1:numel(Ke)
        k = Ke(j);  Fj = fin_of(S.fin, k.name);
        if ~k.ok, continue; end
        p('| %s | %.0f | %.0f | %.1f%% | %s (%+.0f) | %s (%+.0f) | %s | %s | %.1f%% | %s |\n', k.label, ...
          k.E_export / 1000, k.E_grid / 1000, 100 * k.curt_frac, commas(k.P_pv), round(k.P_pv - B.P_pv) + 0, ...
          commas(k.E_b), round(k.E_b - B.E_b) + 0, commas(k.cost), commas(k.savings), 100 * k.savings_frac, ...
          ftxt(Fj, 'npv', 'c'));
    end
    kz = Ke(abs([Ke.c_export]) < 1e-9 & [Ke.ok] & ~strcmp({Ke.name}, 'export_nm'));
    if ~isempty(kz)
        p(['\nAt a price of 0 export has no value: %.1f MWh is exported and the cost is %s $/yr, against ' ...
           '%s $/yr in the base case.\n'], kz(1).E_export / 1000, commas(kz(1).cost), commas(B.cost));
    end
    p(['\nWhere exporting is a tie in cost (price 0, or a credit equal to the tariff, where importing and ' ...
       'exporting in the same hour would cost nothing) a tie-breaker of %g $/kWh on export makes the ' ...
       'model export only what has value. Largest import and export in the same hour over the export ' ...
       'cases: %.1e kW.\n'], s.tie_ex, max([Ke.chk_imp_exp_kW]));
    kn = Ke(strcmp({Ke.name}, 'export_nm'));
    if ~isempty(kn) && kn.ok
        p(['\nNet metering: %.0f MWh exported against %.0f MWh imported, so the grid bill is %s $/yr ' ...
           '(base case %s $/yr). The cost falls by %s $/yr against the base case.\n\n'], ...
           kn.E_export / 1000, kn.E_grid / 1000, commas(kn.c_grid + kn.c_export), commas(B.c_grid), ...
           commas(B.cost - kn.cost));
    else
        p('\n');
    end
end

% ============================================================== finance
p('## Finance: NPV, IRR and payback\n\n');
E = P.economics.npv;
p(['Cash flows in constant USD, unlevered and before tax, over %d years, discounted at the base real ' ...
   'rate of %.2f%%. No loan structure is assumed.\n\n'], Fb.horizon, 100 * Fb.rate);
p(['- Year 0: PV and battery capex. The existing diesel sets are a sunk cost.\n' ...
   '- Years 1 to %d: saving = cash operating cost of the reference minus that of the microgrid. The ' ...
   'operating cost is grid energy, fuel, diesel O&M, PV O&M and battery O&M, less any export credit. ' ...
   'The battery throughput cost is left out: wear is paid for by the replacement.\n' ...
   '- PV output falls by %.1f%% per year. Dispatch is re-optimized with the sizes fixed for years %s, ' ...
   'with the diesel limited to the reference rating (the existing plant), and interpolated linearly ' ...
   'in between.\n' ...
   '- Year %d: battery replaced at %g $/kWh. Year %d: salvage for the remaining life of the PV and of ' ...
   'the second battery, linear.\n\n'], Fb.horizon, P.pv.degradation_pct_yr(2), ...
   list_of(E.pv_degradation_dispatch_years(:)', '%d'), E.battery_replacement_year, ...
   E.battery_replacement_cost_per_kWh(2), Fb.horizon);
p(['Base case: investment %s $ (PV %s, battery %s). Saving %s $ in year 1 and %s $ in year %d. Battery ' ...
   'replacement %s $, salvage %s $. **NPV %s $, IRR %.1f%%, simple payback %.1f years, discounted ' ...
   'payback %.1f years.** With the low battery replacement cost of %g $/kWh the NPV is %s $. The yearly ' ...
   'figures are in `cashflow_base.csv`. The replacement is costed at the base value in every run, also ' ...
   'in the battery-cost sensitivities; `table_finance.csv` gives the NPV with the low value next to ' ...
   'it.\n\n'], commas(Fb.capex0), commas(Fb.capex_pv), commas(Fb.capex_b), ...
   commas(Fb.saving_first), commas(Fb.saving_last), Fb.horizon, commas(Fb.replacement_b), ...
   commas(Fb.salvage), commas(Fb.npv), 100 * Fb.irr, Fb.payback, Fb.payback_disc, ...
   E.battery_replacement_cost_per_kWh(1), commas(Fb.npv_repl_low));
p('NPV of the base case against the discount rate (`fig_npv_vs_rate.png`):\n\n| Rate |');
p(' %.2f%% |', 100 * Fb.curve_rate);
p('\n|---|%s\n| NPV $ |', repmat('---|', 1, numel(Fb.curve_rate)));
for j = 1:numel(Fb.curve_npv), p(' %s |', commas(Fb.curve_npv(j))); end
p('\n\n');
if numel(S.fin) > 1
    p(['| Run | Investment $ | Saving year 1 $ | Saving year %d $ | NPV $ | IRR | Payback yr | ' ...
       'Discounted payback yr |\n|---|---|---|---|---|---|---|---|\n'], Fb.horizon);
    for j = 1:numel(S.fin)
        Fj = S.fin(j).F;
        p('| %s | %s | %s | %s | %s | %s | %s | %s |\n', run_name(S.fin(j).K), commas(Fj.capex0), commas(Fj.saving_first), ...
          commas(Fj.saving_last), commas(Fj.npv), ftxt(Fj, 'irr', '%'), ftxt(Fj, 'payback', 'y'), ...
          ftxt(Fj, 'payback_disc', 'y'));
    end
    p('\n');
    jd = find(strcmp({S.fin.name}, 'diesel_capex'), 1);
    if ~isempty(jd)
        Fd = S.fin(jd).F;  Kd = S.fin(jd).K;
        p(['In the diesel-replacement case both the reference and the microgrid buy new sets, so the ' ...
           'cash flow carries the difference in diesel capex (%s $: the microgrid needs %.0f kW, the ' ...
           'reference %.0f kW), again after %d years, with its salvage. Its later-year dispatch is limited ' ...
           'to the rating that was bought.\n\n'], commas(Fd.capex_d), Kd.P_d, Kd.ref_P_d, s.n_d);
    end
end
allF = [S.fin.F];
[worst, jw] = max([allF.max_lpsp_later]);
p(['Later project years: with the diesel limited to the reference rating no load can go unserved, ' ...
   'because that rating alone carries the peak; what changes is how much diesel is used. The base ' ...
   'case needs %.0f kW of diesel in year 1 and up to %.0f kW in the later years, of the %.0f kW ' ...
   'available. Largest LPSP over all finance runs and years: %.3f%%'], B.P_d, Fb.max_P_d_later, ...
   B.ref_P_d, 100 * worst);
if worst > 0, p(' (run `%s`, whose diesel is limited to the rating it bought)', S.fin(jw).name); end
p('; largest unserved critical energy %.1f kWh.\n\n', max([allF.max_uns_c_later]));
p(['Consistency check for the base case: without PV degradation, replacement and salvage the NPV is ' ...
   '%s $. The annualized-cost saving divided by CRF(i, %d) is %s $. The gap of %s $ has four parts: the ' ...
   'annualized cost spreads the PV over %d years, not %d (%s $), and the battery over %d years (%s $); ' ...
   'the diesel capex difference (%s $); and the throughput cost, which is in the annualized cost only ' ...
   '(%s $). Unexplained: %.0f $.\n\n'], commas(Fb.npv_simple), Fb.horizon, commas(Fb.npv_annualized), ...
   commas(Fb.gap), s.n_pv, Fb.horizon, commas(Fb.gap_pv), s.n_b, commas(Fb.gap_b), commas(Fb.gap_d), ...
   commas(Fb.gap_deg), abs(Fb.gap_unexplained));

if full
    % ======================================================== weather years
    p('## Weather robustness (base-case PV and battery, dispatch re-optimized)\n\n');
    p(['PV yield of each weather year 2014-2023 at tilt %d deg, same load and grid. Main variant: the ' ...
       'diesel is limited to the existing plant, taken as the rating that carries the reference case ' ...
       '(%.0f kW). That rating alone carries the peak, so in this variant no load can go unserved: its ' ...
       'results are the cost and the diesel rating used. Second variant: the diesel is limited to what ' ...
       'the base case needs (%.0f kW); load may be shed at a penalty, so a shortfall shows up as LPSP ' ...
       'above %g%% or as unserved critical load.\n\n'], S.best_tilt, F.P_d, B.P_d, 100 * s.lpsp_max);
    p(['| Year | Cost $/yr | LPSP | Unserved critical kWh | Diesel kW used | Diesel MWh | Second variant: ' ...
       'LPSP | Second variant: unserved critical kWh |\n|---|---|---|---|---|---|---|---|\n']);
    for j = 1:numel(S.years)
        a = S.Kwx(j);  b = S.Kwx_fixed(j);
        p('| %d | %s | %.2f%% | %.1f | %.0f | %.0f | %.2f%% | %.1f |\n', S.years(j), commas(a.cost), ...
          100 * a.lpsp, a.E_uns_c, a.P_d, a.E_diesel / 1000, 100 * b.lpsp, b.E_uns_c);
    end
    [~, jc] = max([S.Kwx.cost]);  [~, jl] = max([S.Kwx_fixed.lpsp]);
    p(['\nMain variant: worst-year cost %s $/yr (%d) against %s $/yr in the design year, worst LPSP ' ...
       '%.2f%%, unserved critical load at most %.1f kWh, diesel rating used up to %.0f kW. Second ' ...
